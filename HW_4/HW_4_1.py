#Дан файл целых чисел, содержащий не менее четырех элементов.Вывести первый, второй,
#предпоследний и последний элементы данного файла. Если чисел меньше 3 выводить ошибку

f = open("file_HW_4_1.txt", "r")
for line in f:
    numbers = line.split()
    if len(numbers) < 3:
        print("Ошибка: количество чисел должно быть больше 3-х")
    else:
        print(numbers[0], numbers[1], numbers[-2], numbers[-1])

f.close()
